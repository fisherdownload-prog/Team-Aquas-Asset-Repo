#!/usr/bin/env python3
"""Write CATALOGUE.md: a one-file index of this asset library, so nobody (human or AI) has to walk
16,000 files to find something.

  python3 tools/build_catalogue.py          rewrite CATALOGUE.md
  python3 tools/build_catalogue.py --check  exit 1 if CATALOGUE.md is out of date

One row per pack (a creator's or project's folder), with a summary from its README. Each tileset
gets its own row with its format, read from metatiles.bin and metatile_attributes.bin. Assets used
by Kanto City are listed in tools/kanto_city_usage.json and marked in the catalogue.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP = {'.git', '.github', 'tools'}


def rel(p):
    return os.path.relpath(p, ROOT)


def readme_summary(folder, deep=True):
    """The first line of prose in the folder's README (or, failing that, the first README below
    it), with markdown removed."""
    for name in ('README.md', 'readme.md', 'Readme.md', 'Credits.md', 'credits.md'):
        p = os.path.join(folder, name)
        if os.path.exists(p):
            for line in open(p, errors='replace'):
                line = re.sub(r'!\[[^\]]*\]\([^)]*\)', '', line)          # images
                line = re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', line)      # links
                line = re.sub(r'<[^>]+>', '', line).strip(' \t\r\n#*>-_|')
                if len(line) > 15 and not line.lower().startswith(('credit', 'preview', 'please credit')):
                    return line[:160] + ('…' if len(line) > 160 else '')
    if deep:
        for d, subdirs, fs in os.walk(folder):
            subdirs.sort()
            if d != folder and any(f.lower() in ('readme.md', 'credits.md') for f in fs):
                found = readme_summary(d, deep=False)
                if found:
                    return found
    return ''


def files_under(folder):
    out = []
    for d, subdirs, fs in os.walk(folder):
        subdirs[:] = sorted(s for s in subdirs if s not in SKIP)
        out += [os.path.join(d, f) for f in fs]
    return out


def kinds(files):
    exts = {}
    for f in files:
        e = os.path.splitext(f)[1].lower().lstrip('.') or 'other'
        exts[e] = exts.get(e, 0) + 1
    return ', '.join(f'{n} {e}' for e, n in sorted(exts.items(), key=lambda kv: -kv[1])[:4])


def tileset_format(folder):
    m = os.path.getsize(os.path.join(folder, 'metatiles.bin'))
    a_path = os.path.join(folder, 'metatile_attributes.bin')
    a = os.path.getsize(a_path) if os.path.exists(a_path) else 0
    for attr_size, game in ((2, 'Emerald'), (4, 'FRLG')):
        if a and a % attr_size == 0:
            count = a // attr_size
            if count and m % (count * 2) == 0 and m // (count * 2) in (8, 12):
                layers = 'triple-layer' if m // (count * 2) == 12 else 'dual-layer'
                return f'{game}, {layers}, {count} metatiles'
    for entries, layers in ((12, 'triple-layer?'), (8, 'dual-layer?')):
        if m % (entries * 2) == 0:
            return f'{layers} {m // (entries * 2)} metatiles, format unclear'
    return 'format unclear'


def main():
    usage = json.load(open(os.path.join(ROOT, 'tools', 'kanto_city_usage.json')))
    out = ['# Catalogue',
           '',
           'Generated by `tools/build_catalogue.py`. Don\'t edit by hand.',
           '',
           'This is an index of everything in this asset library. **Search this file instead of browsing the folders.**',
           'Open a folder only when you\'re choosing an asset from it. ⭐ marks assets Kanto City uses. They\'re',
           'listed in `tools/kanto_city_usage.json`.',
           '']
    cats = sorted(d for d in os.listdir(ROOT) if os.path.isdir(os.path.join(ROOT, d)) and d not in SKIP)
    out += ['| Category | Packs | Files |', '| --- | --- | --- |']
    sections = []
    for cat in cats:
        cpath = os.path.join(ROOT, cat)
        packs = sorted(p for p in os.listdir(cpath) if os.path.isdir(os.path.join(cpath, p)))
        loose = sorted(f for f in os.listdir(cpath) if os.path.isfile(os.path.join(cpath, f)) and not f.lower().endswith('.md'))
        out.append(f'| [{cat}](#{re.sub(r"[^a-z0-9 -]", "", cat.lower()).replace(" ", "-")}) | {len(packs)} | {len(files_under(cpath))} |')
        sec = [f'## {cat}', '']
        if readme_summary(cpath):
            sec += [readme_summary(cpath), '']
        if loose:
            sec += ['Files: ' + ', '.join(f'`{f}`' for f in loose), '']
        if cat == 'Tilesets':
            sec += ['| Tileset | Format | Summary |', '| --- | --- | --- |']
            for d, subdirs, fs in sorted(os.walk(cpath)):
                subdirs.sort()
                if 'metatiles.bin' in fs:
                    star = ' ⭐ ' + usage[rel(d)] if rel(d) in usage else ''
                    sec.append(f'| `{rel(d)}` | {tileset_format(d)} | {readme_summary(d)}{star} |')
            sec += ['', 'Image-only tile packs (no metatiles; you have to assemble the tileset yourself):', '']
            for d, subdirs, fs in sorted(os.walk(cpath)):
                has_meta = any('metatiles.bin' in f for _, _, f in os.walk(d))
                depth = rel(d).count(os.sep)
                if depth == 2 and not has_meta:
                    sec.append(f'- `{rel(d)}`: {kinds(files_under(d))}. {readme_summary(d)}')
        else:
            sec += ['| Pack | Contents | Summary |', '| --- | --- | --- |']
            for p in packs:
                ppath = os.path.join(cpath, p)
                subs = sorted(s for s in os.listdir(ppath) if os.path.isdir(os.path.join(ppath, s)))
                contents = kinds(files_under(ppath))
                if subs:
                    contents += '; folders: ' + ', '.join(subs[:8]) + (f' (+{len(subs) - 8})' if len(subs) > 8 else '')
                star = ' ⭐ ' + usage[rel(ppath)] if rel(ppath) in usage else ''
                sec.append(f'| `{rel(ppath)}` | {contents} | {readme_summary(ppath)}{star} |')
        sections += sec + ['']
    text = '\n'.join(out + [''] + sections).replace('\\', '/')
    path = os.path.join(ROOT, 'CATALOGUE.md')
    if '--check' in sys.argv:
        if not os.path.exists(path) or open(path).read() != text:
            sys.exit('CATALOGUE.md is out of date: run python3 tools/build_catalogue.py')
        return
    open(path, 'w').write(text)
    print(f'CATALOGUE.md: {len(text.splitlines())} lines')


if __name__ == '__main__':
    main()
